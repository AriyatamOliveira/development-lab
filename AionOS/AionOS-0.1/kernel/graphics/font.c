static uint8_t symbol(char c, int r) {
    switch (c) {
    case ' ':
        return 0;
    case '.':
        return r == 6 ? 4 : 0;
    case ',':
        return r == 5 ? 4 : r == 6 ? 8 : 0;
    case ':':
        return r == 2 || r == 5 ? 4 : 0;
    case ';':
        return r == 2 || r == 5 ? 4 : r == 6 ? 8 : 0;
    case '-':
        return r == 3 ? 14 : 0;
    case '_':
        return r == 6 ? 31 : 0;
    case '+':
        return r == 3 ? 14 : r >= 1 && r <= 5 ? 4 : 0;
    case '/':
        return r < 5 ? 1u << (r) : 16;
    case '\\':
        return r < 5 ? 16u >> r : 1;
    case '[':
        return r == 0 || r == 6 ? 14 : 8;
    case ']':
        return r == 0 || r == 6 ? 14 : 2;
    case '(':
        return r == 0 || r == 6 ? 2 : r == 1 || r == 5 ? 4 : 8;
    case ')':
        return r == 0 || r == 6 ? 8 : r == 1 || r == 5 ? 4 : 2;
    case '=':
        return r == 2 || r == 4 ? 31 : 0;
    case '!':
        return r < 4 || r == 6 ? 4 : 0;
    case '?': {
        const uint8_t a[] = {14, 17, 1, 2, 4, 0, 4};
        return a[r];
    }
    case '*':
        return r == 1 || r == 5 ? 21 : r == 2 || r == 4 ? 14 : r == 3 ? 31 : 0;
    case '"':
        return r < 2 ? 10 : 0;
    case '\'':
        return r < 2 ? 4 : 0;
    case '<':
        return r == 1 || r == 5 ? 2 : r == 2 || r == 4 ? 4 : r == 3 ? 8 : 0;
    case '>':
        return r == 1 || r == 5 ? 8 : r == 2 || r == 4 ? 4 : r == 3 ? 2 : 0;
    case '|':
        return 4;
    case '#':
        return r == 2 || r == 4 ? 31 : 10;
    case '%':
        return r == 0 ? 25 : r == 6 ? 19 : 1u << (r < 5 ? r : 4);
    case '@': {
        const uint8_t a[] = {14, 17, 23, 21, 23, 16, 14};
        return a[r];
    }
    case '$': {
        const uint8_t a[] = {4, 15, 20, 14, 5, 30, 4};
        return a[r];
    }
    case '&': {
        const uint8_t a[] = {12, 18, 20, 8, 21, 18, 13};
        return a[r];
    }
    case '^':
        return r == 0 ? 4 : r == 1 ? 10 : 0;
    case '`':
        return r == 0 ? 8 : r == 1 ? 4 : 0;
    case '~':
        return r == 2 ? 10 : r == 3 ? 21 : 0;
    case '{':
        return r == 0 || r == 6 ? 6 : r == 3 ? 8 : 4;
    case '}':
        return r == 0 || r == 6 ? 12 : r == 3 ? 2 : 4;
    default:
        return r == 0 || r == 6 ? 31 : 17;
    }
}
void gfx_char(int x, int y, char c, uint32_t color, int scale) {
    for (int r = 0; r < 7; r++) {
        uint8_t bits = c >= 'A' && c <= 'Z'   ? upper[c - 'A'][r]
                       : c >= 'a' && c <= 'z' ? lower[c - 'a'][r]
                       : c >= '0' && c <= '9' ? digits[c - '0'][r]
                                              : symbol(c, r);
        for (int col = 0; col < 5; col++)
            if (bits & (16 >> col))
                gfx_rect(x + col * scale, y + r * scale, scale, scale, color);
    }
}
void gfx_text(int x, int y, const char *s, uint32_t c, int scale) {
    int origin = x;
    while (*s) {
        if (*s == '\n') {
            y += 9 * scale;
            x = origin;
        } else {
            gfx_char(x, y, *s, c, scale);
            x += 6 * scale;
        }
        s++;
    }
}
